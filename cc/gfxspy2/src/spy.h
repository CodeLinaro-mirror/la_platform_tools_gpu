inline Spy::Spy(uint32_t contextId, Encoder* encoder) :
mContextId(contextId), mEncoder(encoder) {}

template <typename T>
inline void Spy::observe(const T* ptr, uint64_t cnt, order order) {
    const uint64_t size = cnt * sizeof(T);
    Id id(ptr, size);
    if (!observed(id)) {
        mEncoder->Id(RESOURCE_ID);
        mEncoder->Id(id);
        mEncoder->Data(ptr, size);
    }
    mEncoder->Id(OBSERVATION_ID);
    mEncoder->Bool(order == PRE_OBSERVE);
    mEncoder->U64(reinterpret_cast<uint64_t>(ptr));
    mEncoder->U64(size);
}

template <>
inline void Spy::observe(const void *ptr, uint64_t cnt, order order) {
    observe<uint8_t>(reinterpret_cast<const uint8_t*>(ptr), cnt, order);
}

