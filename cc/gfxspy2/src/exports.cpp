    if (strcmp(name, "glGetQueryObjectuivEXT") == 0) { return reinterpret_cast<WGLPROC>(glGetQueryObjectuivEXT); }
    if (strcmp(name, "glGetQueryObjecti64vEXT") == 0) { return reinterpret_cast<WGLPROC>(glGetQueryObjecti64vEXT); }
    if (strcmp(name, "glGetQueryObjectui64vEXT") == 0) { return reinterpret_cast<WGLPROC>(glGetQueryObjectui64vEXT); }

    // TODO: If we reach this code, we're not capturing the command!
    typedef WGLPROC (__stdcall* PFNWGLGETPROCADDRESS)(const char*);
    PFNWGLGETPROCADDRESS wglGetProcAddress = reinterpret_cast<PFNWGLGETPROCADDRESS>(
    gapic::GetGfxProcAddress("wglGetProcAddress"));
